"""Package one seat of a Kaggle replay as a verbatim tape opponent.

Our planner's archetype genes cannot express the day-10 purse of the "class A"
wheat clones that take half our Kaggle games, so we cannot train against a
reconstruction of them.  We can, however, train against the *recording*: a
packaged agent that emits the opponent's per-turn action dict from a replay,
indexed by the engine's step counter.  The immutable kagg2
(../kaggriculture2/main.py) is exactly this and earns ~170k on this engine, so
a fixed action sequence is known to survive replay here.

Why a positional tape transfers across seeds at all: every farm starts
identical -- a 10x10 board whose NW quadrant is empty (`null`) and whose other
three quadrants are `LOCKED`, farmer at (4, 4), no terrain variety -- and both
seats get the same layout.  The seed randomises the *town* (which shops unlock,
in what order), the weed spawns, and therefore the prices, but not a single
tile coordinate the tape names.  What the tape cannot carry over is money: its
SELL revenue depends on prices that our seat also moves, so a HIRE or BUY that
cleared in the original may be refused here, and the engine silently drops it.

Only two runtime repairs are made by default, both of them kagg2's:

  * hands are padded/truncated to the seat's live hand count, because a refused
    HIRE shortens the roster.  (The engine does not reject the action: an
    out-of-range unit order is a silent per-unit no-op -- `_farmer_position`
    returns None and `_apply_unit_action` returns, kaggriculture.py:282/907 --
    so the truncation costs the tape the tail of its crew's orders, it does not
    save the turn from being thrown away.  Measured 2026-09-14.);
  * a step past the end of the tape emits PASS rather than raising.

`--hire-sticky` bakes in a third, OPT-IN repair (`TAPE_HIRE_STICKY=0/1` wins at
run time; the KAGG3_ namespace is cleared for file agents, so the name carries
no prefix).  A refused HIRE is re-issued on the following turns of the same day
until the roster matches the source episode's roster at that step, and hand
orders are addressed by SOURCE hand index through a live->source map instead of
by position.  With the flag off the emitted agent is byte-for-byte the frozen
tape and plays the identical game -- `--from-main` re-cuts an existing package
in the new mode and refuses to write unless that equivalence is proved.

`--hire-sticky-purse` (`TAPE_PURSE_FIX=0/1`) is a fifth, OPT-IN repair, also
hire-sticky-only: the owed-hire re-issue is retried at EVERY later hour of the
same day, including the day's last hour (plain hire-sticky blacks that hour out
because `_src_hands(step + 1)` is already the next day's empty roster), capped
at the source's roster at THAT hour.  It is never carried across midnight: the
engine wipes the roster nightly (kaggriculture.py:880-882), so a hire deferred
past midnight is a different hire and the next day's owed list is recomputed
from the source's own roster.  Measured 2026-09-14 -- it is a no-op on TOPB3,
where hire-sticky already lands 286/286 of the source's hires on every board
(docs/strategy/2026-09-14-tape-purse.md).

`--hire-sticky-remap` (`TAPE_MAP_FIX=0/1`) is a fourth, OPT-IN repair that only
changes hire-sticky runs: the live->source hand map is re-derived every turn, so
a live hand hired AHEAD of the source claims the source's next new hand instead
of PASSing for the rest of the day.  Without it the map is a persistent day-level
assignment and source order k is executed by live hand k+1 from the moment the
seat out-hires its source -- measured on three TOPB3 boards 2026-09-14, worth
-0.35 retention on episode 108741964 (docs/strategy/2026-09-14-tape-map.md).

Usage:
    python scripts/tape_opponent.py <replay.json> [--opponent-team NAME | --seat N]
        -o dist/opponent_tape_<episode>.tar.gz --out-dir <dir>

`--out-dir` writes the same `main.py` unpacked, which is what the eval harness
wants (`--opponents <dir>/main.py`); no tar tooling is needed to use it.
"""

