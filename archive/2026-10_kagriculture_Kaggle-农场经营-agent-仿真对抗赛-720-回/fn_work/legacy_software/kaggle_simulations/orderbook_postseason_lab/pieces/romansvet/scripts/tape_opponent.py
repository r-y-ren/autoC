def load_replay(path: Path) -> dict:
    with open(path) as fh:
        return json.load(fh)


def resolve_seat(replay: dict, team: str | None, seat: int | None,
                 ours: str = "OurTeam") -> int:
    """Which seat to tape.

    `--seat` wins; then an exact or case-insensitive-substring team match; then
    the single seat that is not ours, which is the common case (these replays
    are our own losses, so the interesting seat is the other one).
    """
    names = list((replay.get("info") or {}).get("TeamNames") or [])
    if seat is not None:
        if not 0 <= seat < max(2, len(names)):
            raise SystemExit(f"seat {seat} out of range for {names}")
        return seat
    if team is not None:
        for i, name in enumerate(names):
            if name == team:
                return i
        hits = [i for i, name in enumerate(names) if team.lower() in name.lower()]
        if len(hits) == 1:
            return hits[0]
        raise SystemExit(f"--opponent-team {team!r} matched {len(hits)} of {names}")
    hits = [i for i, name in enumerate(names) if name != ours]
    if len(hits) != 1:
        raise SystemExit(f"cannot infer the opponent seat from {names}; pass --seat")
    return hits[0]


def extract_tape(replay: dict, seat: int) -> list[dict]:
    """Actions this seat took, indexed by the engine step they were taken at.

    `steps[t][seat]["action"]` is the action that *produced*
    `steps[t][seat]["observation"]`, so it was computed from the step-(t-1)
    observation and is the action of engine step t-1.  `steps[0]`'s action is
    the loader's placeholder and is dropped.  A refused turn (status INVALID /
    ERROR / TIMEOUT) is recorded as `None`; it becomes a PASS, which is what
    the engine did with it.
    """
    steps = replay["steps"]
    tape = []
    for t in range(1, len(steps)):
        action = steps[t][seat].get("action")
        if not isinstance(action, dict):
            action = {}
        tape.append({
            "farmer": list(action.get("farmer") or ["PASS"]),
            "hands": [list(order or ["PASS"]) for order in (action.get("hands") or [])],
            "market": [list(order) for order in (action.get("market") or [])],
        })
    return tape


def extract_town(replay: dict) -> list:
    """The recorded town schedule as `[[day, "SHOP_NAME"], ...]`.

    `observation["town"]` carries exactly one key, `unlocked_shops`: the list
    the engine appends to in `_end_of_day`, in unlock order, with repeats (shops
    are drawn WITH replacement, so the same name can appear more than once).
    There are no shop-local demand rows in the observation -- a shop's demand is
    a constant of its type (`SHOPS` in the engine, `spec._SHOP_DEMAND` here) --
    so the schedule is the whole of the town's state.

    The list is reduced to one `(day, shop)` per unlock by diffing consecutive
    steps and reading the day off the observation the growth first appears in.
    That day is the engine's `next_day`, i.e. the first day the shop is visible
    and sells; `_end_of_day(day)` appended it at the end of `day - 1`.
    """
    out, prev = [], []
    for step in replay["steps"]:
        obs = step[0]["observation"]
        town = obs.get("town") or {}
        shops = list(town.get("unlocked_shops") or [])
        if len(shops) > len(prev):
            day = int(obs.get("day") or 0)
            for name in shops[len(prev):]:
                out.append([day, str(name)])
        prev = shops
    return out


def load_main(path: Path) -> dict:
    """Recover a tape (and its provenance) from a main.py this script wrote.

    The replays are ~30 MB and stay out of the tree, so re-cutting an existing
    tape in a new mode has to start from the packaged agent, not the source
    episode.  Exec'ing it is exactly how the engine loads it, and `_TOWN` comes
    back with everything else, so a `--with-town` package stays pinned.
    """
    ns: dict = {}
    exec(compile(path.read_text(), str(path), "exec"), ns)  # noqa: S102
    opp = "?"
    for line in (ns.get("__doc__") or "").splitlines():
        if line.startswith("against "):
            opp = line[len("against "):].rstrip(".")
    return {"tape": ns["_TAPE"], "episode": ns["_EPISODE"], "seat": ns["_SOURCE_SEAT"],
            "team": ns["_SOURCE_TEAM"], "final_money": ns["_SOURCE_MONEY"],
            "town": ns.get("_TOWN") or [], "opp_team": opp}


def load_agent(main_py: str, hire_sticky: bool | None = None) -> dict:
    """Exec the emitted file the way kaggle_environments does, with
    TAPE_HIRE_STICKY pinned for the question the caller is asking."""
    if hire_sticky is not None:
        os.environ["TAPE_HIRE_STICKY"] = "1" if hire_sticky else "0"
    ns: dict = {}
    exec(compile(main_py, "<tape>", "exec"), ns)  # noqa: S102
    return ns


def render_main(tape: list[dict], episode: int, seat: int, team: str,
                opp_team: str, final_money: float, town=None,
                hire_sticky: bool = False, map_fix: bool = False,
                purse_fix: bool = False) -> str:
    raw = json.dumps(tape, separators=(",", ":")).encode("utf-8")
    blob = base64.b85encode(zlib.compress(raw, 9)).decode("ascii")
    # b85 has no quote characters, so the blob is safe inside the "..." above;
    # wrap it so the emitted file stays diffable.
    wrapped = '"\n    "'.join(blob[i:i + 92] for i in range(0, len(blob), 92))
    return MAIN_TEMPLATE.format(
        blob=wrapped, n=len(tape), episode=episode, seat=seat, team=team,
        opp_team=opp_team, final_money=int(final_money),
        town=[list(row) for row in (town or [])],
        hire_sticky=bool(hire_sticky), map_fix=bool(map_fix),
        purse_fix=bool(purse_fix),
    ).replace("#__HIRE_FIX__", HIRE_FIX_CODE)


def verify(main_py: str, replay: dict, seat: int) -> int:
    """Feed the emitted agent every recorded pre-state and count disagreements.

    Cheap and fixture-free (the replays are ~30 MB and stay out of the tree),
    and it is the check that actually matters: it catches an off-by-one in the
    step index, which nothing downstream would flag -- a tape shifted by one
    turn still plays a plausible-looking game.
    """
    # exec on purpose: this is exactly how kaggle_environments loads the file,
    # so the check exercises the module the engine will see, not an import of
    # it.  Hire-sticky is forced off: this asks whether the TAPE is right, not
    # what the reflex does with it.
    ns = load_agent(main_py, hire_sticky=False)
    agent, align, hand_count = ns["agent"], ns["_align"], ns["_hand_count"]
    steps = replay["steps"]
    bad = 0
    for t in range(len(steps) - 1):
        obs = dict(steps[t][seat]["observation"])
        obs.setdefault("player", seat)
        want = steps[t + 1][seat].get("action")
        # Compare through the same hand alignment the tape applies: a turn the
        # engine refused is recorded as a null action, and replaying it as PASS
        # for the live roster is the intended behaviour, not a disagreement.
        expected = align(want if isinstance(want, dict) else {}, hand_count(obs))
        if agent(obs) != expected:
            bad += 1
    return bad


def verify_frozen_match(new_main: str, old_main: str, max_hands: int = 14) -> int:
    """Count (step, roster) pairs where the new file, flag off, differs from the old.

    The frozen agent is a pure function of (step, live hand count), so sweeping
    every step against every plausible roster size is an exhaustive equivalence
    proof -- stronger than a replay, and it needs no replay to run.
    """
    new_ns = load_agent(new_main, hire_sticky=False)
    old_ns = load_agent(old_main, hire_sticky=False)
    bad = 0
    for step in range(len(new_ns["_TAPE"]) + 2):
        for hands in range(max_hands + 1):
            obs = {"step": step, "player": 0,
                   "farms": [{"hands": [[0, 0]] * hands}, {"hands": []}]}
            if new_ns["agent"](obs) != old_ns["agent"](obs):
                bad += 1
    return bad


def write_tar(main_py: str, out: Path) -> Path:
    """Deterministic archive: zeroed mtime/uid/gid and a gzip header with
    mtime=0, so two builds of the same replay hash the same (the same contract
    scripts/package_submission.py holds itself to)."""
    out.parent.mkdir(parents=True, exist_ok=True)
    data = main_py.encode("utf-8")
    with open(out, "wb") as raw, gzip.GzipFile(
            filename="", mode="wb", fileobj=raw, compresslevel=9, mtime=0) as gz, \
            tarfile.open(fileobj=gz, mode="w") as tf:
        info = tarfile.TarInfo("main.py")
        info.size = len(data)
        info.mtime = 0
        info.uid = info.gid = 0
        info.uname = info.gname = ""
        info.mode = 0o644
        tf.addfile(info, io.BytesIO(data))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("replay", type=Path, nargs="?")
    ap.add_argument("--from-main", type=Path,
                    help="re-cut a main.py this script wrote (no replay needed); "
                         "its _TAPE, _TOWN and provenance are carried over")
    ap.add_argument("--opponent-team", help="team name (exact, or a unique substring)")
    ap.add_argument("--seat", type=int, help="seat index; wins over --opponent-team")
    ap.add_argument("--ours", default="OurTeam",
                    help="our team name, used to infer the opponent seat")
    ap.add_argument("-o", "--out", type=Path,
                    help="tar.gz to write (default dist/opponent_tape_<episode>.tar.gz)")
    ap.add_argument("--out-dir", type=Path,
                    help="also write main.py unpacked here, for --opponents <dir>/main.py")
    ap.add_argument("--with-town", action="store_true",
                    help="also record the town this seat played in (the "
                         "per-unlock-day shop list) as the package's `_TOWN` "
                         "constant, for a harness that pins it; off by default, "
                         "and a package cut without it is byte-identical to one "
                         "cut before the flag existed")
    ap.add_argument("--hire-sticky", action="store_true",
                    help="bake in HIRE-STICKY mode: re-issue a refused HIRE on "
                         "the following turns of the same day until the roster "
                         "matches the source episode's, never past it, and "
                         "address hand orders by source hand index "
                         "(TAPE_HIRE_STICKY=0/1 wins at run time)")
    ap.add_argument("--hire-sticky-remap", action="store_true",
                    help="bake in the MAP-REMAP repair on top of HIRE-STICKY: "
                         "re-derive the live->source hand map every turn so a "
                         "live hand hired ahead of the source claims the "
                         "source's next new hand instead of PASSing for the "
                         "rest of the day (TAPE_MAP_FIX=0/1 wins at run time; "
                         "inert unless hire-sticky is on)")
    ap.add_argument("--hire-sticky-purse", action="store_true",
                    help="bake in the PURSE repair on top of HIRE-STICKY: retry "
                         "an owed hire at every later hour of the same day, the "
                         "day's LAST hour included (plain hire-sticky blacks it "
                         "out), capped at the source's roster at that hour and "
                         "never carried across midnight (TAPE_PURSE_FIX=0/1 wins "
                         "at run time; inert unless hire-sticky is on)")
    ap.add_argument("--no-verify", action="store_true",
                    help="skip replaying the tape back over the recorded pre-states")
    args = ap.parse_args(argv)

    if (args.replay is None) == (args.from_main is None):
        raise SystemExit("pass exactly one of <replay.json> or --from-main")

    replay = None
    if args.from_main is not None:
        src = load_main(args.from_main)
        seat, episode, tape = src["seat"], src["episode"], src["tape"]
        names = ([src["team"], src["opp_team"]] if seat == 0
                 else [src["opp_team"], src["team"]])
        final_money, town = src["final_money"], src["town"]
    else:
        replay = load_replay(args.replay)
        seat = resolve_seat(replay, args.opponent_team, args.seat, args.ours)
        names = list((replay.get("info") or {}).get("TeamNames") or ["", ""])
        episode = int((replay.get("info") or {}).get("EpisodeId") or 0)
        tape = extract_tape(replay, seat)
        final_money = replay["steps"][-1][0]["observation"]["farms"][seat]["money"]
        town = extract_town(replay) if args.with_town else None

    main_py = render_main(tape, episode, seat, names[seat], names[1 - seat],
                          final_money, town=town, hire_sticky=args.hire_sticky,
                          map_fix=args.hire_sticky_remap,
                          purse_fix=args.hire_sticky_purse)
    if not args.no_verify:
        if replay is not None:
            bad = verify(main_py, replay, seat)
            if bad:
                raise SystemExit(f"tape disagrees with the replay on {bad}/{len(tape)} steps")
        else:
            # No replay to check against, so check what is actually at stake:
            # with the flag off this file must play the source file's game
            # move for move, at every step and every roster size.
            bad = verify_frozen_match(main_py, args.from_main.read_text())
            if bad:
                raise SystemExit(f"re-cut file differs from {args.from_main} on "
                                 f"{bad} (step, roster) pairs with the flag off")
    out = args.out or Path("dist") / f"opponent_tape_{episode}.tar.gz"
    write_tar(main_py, out)
    if args.out_dir:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        (args.out_dir / "main.py").write_text(main_py)

    acting = sum(1 for f in tape
                 if f["market"] or f["farmer"][0] != "PASS"
                 or any(h[0] != "PASS" for h in f["hands"]))
    print(f"episode {episode} seat {seat} ({names[seat]}) vs {names[1 - seat]}: "
          f"{len(tape)} steps, {acting} acting, {int(final_money)} coins"
          f"{'' if args.no_verify else (', verified' if replay is not None else ', frozen-identical')}"f"{', HIRE-STICKY' if args.hire_sticky else ''}"
          f"{', MAP-REMAP' if args.hire_sticky_remap else ''}"
          f"{', PURSE' if args.hire_sticky_purse else ''}"
          f"{f', town {len(town)} unlocks' if town else ''} -> {out}"
          + (f", {args.out_dir}/main.py" if args.out_dir else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
